"""Writes tests/stem_reference.hpp from the song corpus's features_ref.json: per group of records,
the median and quartiles of the drum-stem features tests/stem_features.hpp measures (as numpy's
linear percentiles). Only numbers leave the corpus; no audio is copied.

    python3 -I tools/stem_reference.py /path/to/song-corpus/features_ref.json > tests/stem_reference.hpp
"""
import json
import sys

GROUPS = [('GBV_lofi', 'basement four-track records'), ('OTC', 'home-studio psych records')]
FEATURES = ['centroid_hz', 'rolloff85_hz', 'low_share_db', 'crest100_db', 'corr']


def percentile(values, q):
    v = sorted(values)
    at = (len(v) - 1) * q / 100.0
    lo = int(at)
    hi = min(lo + 1, len(v) - 1)
    return v[lo] + (v[hi] - v[lo]) * (at - lo)


def main():
    data = json.load(open(sys.argv[1]))
    out = ['// Generated by tools/stem_reference.py from the song corpus measured from the user\'s own records',
           '// (htdemucs_6s drum stems of 45 s excerpts; song-corpus/scripts/features.py). Numbers only.',
           '#pragma once', '', '#include <array>', '', 'namespace stem {', '',
           'struct Stat { double q25, median, q75; };',
           'struct Reference {',
           '  const char* group;',
           '  const char* records;',
           '  int tracks;',
           '  Stat centroid_hz, rolloff85_hz, low_share_db, crest100_db, corr;',
           '};', '',
           'inline constexpr std::array kReferences{']
    for group, records in GROUPS:
        drums = [v['drums'] for k, v in sorted(data.items()) if k.startswith(group + '_') and 'drums' in v]
        stats = []
        for name in FEATURES:
            values = [d[name] for d in drums if d.get(name) is not None]
            stats.append('{%.4g, %.4g, %.4g}' % (percentile(values, 25), percentile(values, 50), percentile(values, 75)))
        out.append('    Reference{"%s", "%s", %d, %s},' % (group, records, len(drums), ', '.join(stats)))
    out += ['};', '', '}  // namespace stem', '']
    sys.stdout.write('\n'.join(out))


if __name__ == '__main__':
    main()
